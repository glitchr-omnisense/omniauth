<?php

/**
 * The harness's composer.json and phpunit.xml: this core from its checkout,
 * each method package from a checkout under /omniauth/plugins when there is
 * one, from GitHub (branch 1.x) otherwise; every package's tests in one run.
 * scheb/2fa is a development dependency here only: the trusted-device tests
 * compare omniauth's tokens with its JwtTokenEncoder's, omniauth/totp's its
 * TOTP codes; a method package adds its own (plugins.php). Files are rewritten
 * only when they change, so the entrypoint knows when to install.
 */
$plugins = require __DIR__.'/plugins.php';
$core = '/omniauth/core';
$local = '/omniauth/plugins';
$out = '/harness';

$repositories = [['type' => 'path', 'url' => $core, 'options' => ['symlink' => true, 'versions' => ['omniscient/omniauth' => '1.x-dev']]]];
$require = ['omniscient/omniauth' => '1.x-dev'];
$tests = ['Omniauth\\Tests\\' => "$core/Tests/"];
$suites = ['core' => "$core/Tests"];
$packages = [];
$dev = [];
foreach ($plugins as $slug => $plugin) {
    [$testsNs, $needs] = $plugin + [1 => []];
    $dev += $needs;
    $name = "omniauth/$slug";
    $dir = "$local/$slug";
    $meta = is_file("$dir/composer.json") ? json_decode((string) file_get_contents("$dir/composer.json"), true) : null;
    if (($meta['name'] ?? null) === $name) {
        $repositories[] = ['type' => 'path', 'url' => $dir, 'options' => ['symlink' => true, 'versions' => [$name => '1.x-dev']]];
        $testDir = "$dir/Tests";
        $packages[$slug] = 'checkout';
    } else {
        // A plain git clone over HTTPS: no GitHub API (anonymous calls are rate limited), no ssh in the image.
        $repositories[] = ['type' => 'git', 'url' => "https://github.com/glitchr-studio/omniauth-$slug.git"];
        $testDir = "$out/vendor/omniauth/$slug/Tests";
        $packages[$slug] = 'github';
    }
    $require[$name] = '1.x-dev';
    $tests[$testsNs] = $testDir.'/';
    $suites[$slug] = $testDir;
}

$composer = [
    'name' => 'omniscient/omniauth-harness',
    'description' => 'omniscient/omniauth with every method package: generated by docker/harness/setup.php, do not edit.',
    'type' => 'project',
    'license' => 'MIT',
    'repositories' => $repositories,
    'require' => $require + ['php' => '>=8.2'],
    'require-dev' => [
        'phpunit/phpunit' => '^11.0',
        'scheb/2fa' => '^8.0',
        'symfony/cache' => '^6.4|^7.0|^8.0',
    ] + $dev,
    'autoload-dev' => ['psr-4' => $tests],
    'minimum-stability' => 'dev',
    'prefer-stable' => true,
    'config' => ['sort-packages' => true],
];
$json = json_encode($composer, \JSON_PRETTY_PRINT | \JSON_UNESCAPED_SLASHES)."\n";
if (!is_file("$out/composer.json") || file_get_contents("$out/composer.json") !== $json) {
    file_put_contents("$out/composer.json", $json);
    echo 'composer.json composed', $packages ? ': '.implode(', ', array_map(static fn ($s, $f) => "$s ($f)", array_keys($packages), $packages)) : ' (the core alone)', "\n";
}

$xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<phpunit xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" xsi:noNamespaceSchemaLocation=\"vendor/phpunit/phpunit/phpunit.xsd\" bootstrap=\"vendor/autoload.php\" colors=\"true\" failOnWarning=\"true\" failOnRisky=\"true\" cacheDirectory=\".phpunit.cache\">\n    <testsuites>\n";
foreach ($suites as $suite => $dir) {
    $xml .= "        <testsuite name=\"$suite\"><directory>$dir</directory></testsuite>\n";
}
$xml .= "    </testsuites>\n</phpunit>\n";
if (!is_file("$out/phpunit.xml") || file_get_contents("$out/phpunit.xml") !== $xml) {
    file_put_contents("$out/phpunit.xml", $xml);
}
